// Package presetfile reads slicer preset files. It finds the slicer and the kind of preset from the content, checks
// the limits, removes the printer connection secrets, and extracts the key settings. The upload processing uses it.
package presetfile

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"
)

const (
	maxSize  = 1 << 20  // the largest preset file, in bytes
	maxKeys  = 5000     // a PrusaSlicer print preset has about 200
	maxKey   = 100      // the longest setting name, in bytes
	maxValue = 64 << 10 // the longest setting value (G-code), in bytes
)

// File is a preset file that Parse accepted.
type File struct {
	Slicer   string            // prusaslicer, superslicer or orcaslicer (OrcaSlicer and Bambu Studio share one format)
	Kind     string            // print, filament, printer, or config for a PrusaSlicer file with all three
	Version  string            // the slicer version from the file, or empty
	Inherits string            // the system preset that this one changes, or empty
	Settings map[string]string // every setting except the secrets; a list value is joined with commas
	Removed  []string          // the connection secrets that had a value and were removed, sorted
	Key      []Setting         // the key settings, in the order of keyTable
	Clean    []byte            // the file without the secrets: the copy to store and to download
}

var (
	prusaHeader = regexp.MustCompile(`^# generated by (PrusaSlicer|SuperSlicer) ([0-9][0-9A-Za-z.+-]*) `)
	keyName     = regexp.MustCompile(`^[a-z0-9_]+$`)
	orcaKinds   = map[string]string{"process": "print", "filament": "filament", "machine": "printer"}
)

// errNotPreset is the answer for a file that is neither format.
var errNotPreset = errors.New("the file is not a preset from PrusaSlicer, SuperSlicer, OrcaSlicer or Bambu Studio")

// Parse reads a preset file from its content, never its name. The error text says why a file is refused, so the
// upload processing can show it to the uploader.
func Parse(data []byte) (File, error) {
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf")) // a byte order mark that some editors add
	switch {
	case len(data) == 0:
		return File{}, errors.New("the file is empty")
	case len(data) > maxSize:
		return File{}, errors.New("the file is larger than 1 MB")
	case !utf8.Valid(data) || bytes.IndexByte(data, 0) >= 0:
		return File{}, errors.New("the file is not plain text")
	}
	var f File
	var err error
	if trimmed := bytes.TrimLeft(data, " \t\r\n"); len(trimmed) > 0 && trimmed[0] == '{' {
		f, err = readOrca(trimmed)
	} else {
		f, err = readPrusa(string(data))
	}
	if err != nil {
		return File{}, err
	}
	f.Key = keySettings(f.Settings)
	return f, nil
}

// add checks one setting against the limits and stores it. readPrusa and readOrca call it for each setting.
func (f *File) add(key, value string) error {
	switch {
	case len(key) > maxKey || !keyName.MatchString(key):
		return fmt.Errorf("the setting name %.40q is not a slicer setting", key)
	case len(value) > maxValue:
		return fmt.Errorf("the setting %s is longer than 64 KB", key)
	case len(f.Settings) >= maxKeys:
		return fmt.Errorf("the file has more than %d settings", maxKeys)
	}
	if _, twice := f.Settings[key]; twice {
		return fmt.Errorf("the setting %s is in the file twice", key)
	}
	f.Settings[key] = value
	return nil
}

// secret says if a setting is part of the printer's network connection, which a shared preset must never carry.
func secret(key string) bool {
	return strings.HasPrefix(key, "print_host") || strings.HasPrefix(key, "printhost")
}

// readPrusa reads the "key = value" format of PrusaSlicer and SuperSlicer, and writes the clean copy line by line.
func readPrusa(text string) (File, error) {
	lines := strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
	m := prusaHeader.FindStringSubmatch(lines[0])
	if m == nil {
		return File{}, errNotPreset
	}
	f := File{Slicer: strings.ToLower(m[1]), Version: m[2], Settings: map[string]string{}}
	var clean strings.Builder
	clean.WriteString(lines[0] + "\n")
	for i, line := range lines[1:] {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, " =")
		if !ok {
			return File{}, fmt.Errorf("line %d of the file is not a setting", i+2)
		}
		value = strings.TrimPrefix(value, " ")
		if secret(key) {
			f.drop(key, strings.Trim(value, `"`))
			continue
		}
		if err := f.add(key, value); err != nil {
			return File{}, err
		}
		clean.WriteString(line + "\n")
	}
	kinds := 0
	for _, kind := range []string{"print", "filament", "printer"} {
		if _, ok := f.Settings[kind+"_settings_id"]; ok {
			f.Kind = kind
			kinds++
		}
	}
	switch kinds {
	case 0, 2:
		return File{}, errors.New("the file is not a print, filament or printer preset")
	case 3:
		f.Kind = "config"
	}
	f.Inherits = strings.Trim(f.Settings["inherits"], `"`)
	f.Clean = []byte(clean.String())
	return f, nil
}

// readOrca reads the JSON format of OrcaSlicer and Bambu Studio: one object of strings and lists of strings.
func readOrca(data []byte) (File, error) {
	var obj map[string]any
	if err := json.Unmarshal(data, &obj); err != nil {
		return File{}, errNotPreset
	}
	typ, _ := obj["type"].(string)
	kind, ok := orcaKinds[typ]
	if !ok {
		return File{}, errNotPreset
	}
	f := File{Slicer: "orcaslicer", Kind: kind, Settings: map[string]string{}}
	kept := map[string]any{}
	for key, raw := range obj {
		var value string
		switch v := raw.(type) {
		case string:
			value = v
		case []any:
			items := make([]string, 0, len(v))
			for _, item := range v {
				s, ok := item.(string)
				if !ok {
					return File{}, fmt.Errorf("the setting %.40s has a value that is not text", key)
				}
				items = append(items, s)
			}
			value = strings.Join(items, ",")
		default:
			return File{}, fmt.Errorf("the setting %.40s has a value that is not text", key)
		}
		if secret(key) {
			f.drop(key, value)
			continue
		}
		if err := f.add(key, value); err != nil {
			return File{}, err
		}
		kept[key] = raw
	}
	f.Version = f.Settings["version"]
	f.Inherits = f.Settings["inherits"]
	var clean bytes.Buffer
	enc := json.NewEncoder(&clean)
	enc.SetEscapeHTML(false) // keep "<" and ">" in G-code as the slicer wrote them
	enc.SetIndent("", "    ")
	if err := enc.Encode(kept); err != nil {
		return File{}, fmt.Errorf("write the clean copy: %w", err)
	}
	f.Clean = clean.Bytes()
	return f, nil
}

// drop records a removed secret when it had a value, so the uploader learns what the site left out.
func (f *File) drop(key, value string) {
	if value != "" {
		f.Removed = append(f.Removed, key)
		slices.Sort(f.Removed)
	}
}
