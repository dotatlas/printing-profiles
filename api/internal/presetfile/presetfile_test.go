// fixture reads one file from testdata.
func fixture(t *testing.T, name string) []byte {
	t.Helper()
	data, err := os.ReadFile("testdata/" + name)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// keyValues gives the key settings of a file as "id=value unit" strings, in the fixed order of the table.
func keyValues(f File) []string {
	var out []string
	for _, s := range f.Key {
		out = append(out, strings.TrimSpace(s.ID+"="+s.Value+" "+s.Unit))
	}
	return out
}

func TestReadsAPrusaSlicerFilamentPreset(t *testing.T) {
	f, err := Parse(fixture(t, "prusa-filament.ini"))
	if err != nil {
		t.Fatal(err)
	}
	if f.Slicer != "prusaslicer" || f.Version != "2.9.6" || f.Kind != "filament" || f.Inherits != "Generic PLA @COREONE HF0.4" {
		t.Fatalf("got %s %s %s %q", f.Slicer, f.Version, f.Kind, f.Inherits)
	}
	// "nil" means "use the printer's value", so the retraction is not a key setting of this file.
	want := []string{
		"nozzle_temperature_first_layer=215 °C", "nozzle_temperature=210 °C",
		"bed_temperature_first_layer=65 °C", "bed_temperature=60 °C",
		"fan_min=85 %", "fan_max=100 %", "filament_type=PLA",
	}
	if got := keyValues(f); !slices.Equal(got, want) {
		t.Fatalf("key settings:\n got %q\nwant %q", got, want)
	}
	// G-code stays text, with its escapes as the file has them.
	if f.Settings["start_filament_gcode"] != `"M572 S0.03\nM900 K0"` {
		t.Fatalf("gcode: %q", f.Settings["start_filament_gcode"])
	}
}

func TestDropsThePrinterConnectionSecrets(t *testing.T) {
	for _, name := range []string{"prusa-printer.ini", "orca-machine.json"} {
		f, err := Parse(fixture(t, name))
		if err != nil {
			t.Fatal(err)
		}
		for key := range f.Settings {
			if strings.HasPrefix(key, "print_host") || strings.HasPrefix(key, "printhost") {
				t.Errorf("%s: %s is still in the settings", name, key)
			}
		}
		if f.Kind != "printer" {
			t.Errorf("%s: kind %s", name, f.Kind)
		}
		t.Logf("%s removed %v", name, f.Removed)
	}
	f, _ := Parse(fixture(t, "prusa-printer.ini"))
	// Only keys that held a value are reported; the empty API key is dropped without a word.
	if want := []string{"print_host", "printhost_password", "printhost_user"}; !slices.Equal(f.Removed, want) {
		t.Fatalf("removed %v, want %v", f.Removed, want)
	}
	// A per-extruder list gives the first extruder's value.
	if got := keyValues(f); !slices.Equal(got, []string{"retraction_length=0.7 mm", "retraction_speed=45 mm/s", "nozzle_diameter=0.4 mm"}) {
		t.Fatalf("key settings %q", got)
	}
}

func TestTheCleanCopyLeavesOutTheSecretsAndKeepsTheRest(t *testing.T) {
	f, _ := Parse(fixture(t, "prusa-printer.ini"))
	clean := string(f.Clean)
	if strings.Contains(clean, "hunter2") || strings.Contains(clean, "192.168.1.20") || strings.Contains(clean, "printhost_") {
		t.Fatalf("a secret is in the clean copy:\n%s", clean)
	}
	if !strings.HasPrefix(clean, "# generated by PrusaSlicer 2.9.6") || !strings.Contains(clean, "retract_length = 0.7\n") {
		t.Fatalf("the clean copy lost the header or a setting:\n%s", clean)
	}
	// The clean copy is a preset that reads back to the same settings.
	again, err := Parse(f.Clean)
	if err != nil || len(again.Removed) != 0 || len(again.Settings) != len(f.Settings) {
		t.Fatalf("clean copy reads as %v, %v, %d settings", err, again.Removed, len(again.Settings))
	}

	o, _ := Parse(fixture(t, "orca-machine.json"))
	var back map[string]any
	if err := json.Unmarshal(o.Clean, &back); err != nil {
		t.Fatal(err)
	}
	if _, ok := back["printhost_apikey"]; ok || back["name"] != "Bambu Lab P1S 0.4 nozzle - quiet" {
		t.Fatalf("orca clean copy: %v", back)
	}
}

func TestReadsASuperSlicerPrintPreset(t *testing.T) {
	f, err := Parse(fixture(t, "superslicer-print.ini"))
	if err != nil {
		t.Fatal(err)
	}
	if f.Slicer != "superslicer" || f.Version != "2.5.59.13" || f.Kind != "print" {
		t.Fatalf("got %s %s %s", f.Slicer, f.Version, f.Kind)
	}
	// A relative speed ("50%") has no unit; a plain number gets one.
	want := []string{
		"layer_height=0.2 mm", "first_layer_height=0.2 mm", "walls=3", "top_layers=5", "bottom_layers=4",
		"infill_density=15%", "infill_pattern=gyroid", "outer_wall_speed=50%", "infill_speed=120 mm/s",
	}
	if got := keyValues(f); !slices.Equal(got, want) {
		t.Fatalf("key settings:\n got %q\nwant %q", got, want)
	}
}

