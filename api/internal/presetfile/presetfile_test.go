func TestRefusesWhatIsNotAPreset(t *testing.T) {
	header := "# generated by PrusaSlicer 2.9.6 on 2026-07-22 at 19:42:46 UTC\n"
	cases := map[string]string{
		"empty":                 "",
		"plain text":            "hello, this is not a preset\n",
		"html":                  "<!doctype html><script>alert(1)</script>",
		"no header":             "layer_height = 0.2\nprint_settings_id = \n",
		"a line without =":      header + "layer_height = 0.2\nnot a setting\nprint_settings_id = \n",
		"a bad key":             header + "Layer Height = 0.2\nprint_settings_id = \n",
		"a key twice":           header + "layer_height = 0.2\nlayer_height = 0.3\nprint_settings_id = \n",
		"no kind":               header + "layer_height = 0.2\n",
		"a nul byte":            header + "layer_height = 0.2\x00\nprint_settings_id = \n",
		"bad utf-8":             header + "layer_height = \xff\xfe\nprint_settings_id = \n",
		"too big":               header + strings.Repeat("a", maxSize),
		"a long key":            header + strings.Repeat("k", maxKey+1) + " = 1\nprint_settings_id = \n",
		"a long value":          header + "start_gcode = " + strings.Repeat("G", maxValue+1) + "\nprint_settings_id = \n",
		"json array":            `[{"type":"filament"}]`,
		"json without type":     `{"name":"x","layer_height":"0.2"}`,
		"json unknown type":     `{"type":"plate","name":"x"}`,
		"json number value":     `{"type":"filament","name":"x","nozzle_temperature":215}`,
		"json nested object":    `{"type":"filament","name":"x","extra":{"a":"b"}}`,
		"json array of numbers": `{"type":"filament","name":"x","nozzle_temperature":[215]}`,
	}
	var many strings.Builder
	many.WriteString(header + "print_settings_id = \n")
	for i := 0; i <= maxKeys; i++ {
		many.WriteString("k" + strings.Repeat("x", i%7) + "_" + strconv.Itoa(i) + " = 1\n")
	}
	cases["too many keys"] = many.String()

	for name, data := range cases {
		if f, err := Parse([]byte(data)); err == nil {
			t.Errorf("%s: accepted as %s %s", name, f.Slicer, f.Kind)
		} else if err.Error() == "" {
			t.Errorf("%s: an error without a reason", name)
		}
	}
}
